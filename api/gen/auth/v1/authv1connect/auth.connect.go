// OrganizationServiceClient is a client for the auth.v1.OrganizationService service.
type OrganizationServiceClient interface {
	// Creates a top-level organization and adds the caller to it as platform_admin
	// of the new organization, so the creator can keep working in it immediately.
	// The membership write is best effort: if it fails, the organization still
	// exists and the call reports success, so confirm membership afterwards.
	// Not idempotent: there is no deduplication key and names are not unique, so a
	// retry after a lost response creates a second organization.
	// Fails INTERNAL on a store fault; the name is not required to be unique.
	// Requires platform_admin (enforced in the handler as well as by policy).
	CreateOrganization(context.Context, *connect.Request[v1.CreateOrganizationRequest]) (*connect.Response[v1.CreateOrganizationResponse], error)
	// Reads one organization by identifier.
	// Read-only and replayable; NOT_FOUND for an unknown identifier.
	// Requires organization/read.
	GetOrganization(context.Context, *connect.Request[v1.GetOrganizationRequest]) (*connect.Response[v1.GetOrganizationResponse], error)
	// Lists every organization in the deployment.
	// Read-only, replayable and unpaginated: the answer grows with the deployment,
	// and although policy must be granted in the caller's own domain, the result is
	// not narrowed to organizations the caller belongs to.
	// Requires organization/read.
	ListOrganizations(context.Context, *connect.Request[v1.ListOrganizationsRequest]) (*connect.Response[v1.ListOrganizationsResponse], error)
	// Renames an organization under optimistic locking.
	// Concurrent-conflict semantics: expected_version must match the stored version
	// or the write is refused with ABORTED (optimistic lock conflict); re-read and
	// retry.
	// A disabled organization cannot be updated: FAILED_PRECONDITION.
	// NOT_FOUND for an unknown organization.
	// Requires organization/write.
	UpdateOrganization(context.Context, *connect.Request[v1.UpdateOrganizationRequest]) (*connect.Response[v1.UpdateOrganizationResponse], error)
	// Disables an organization, which stops its members acting on anything scoped to
	// it. There is no re-enable procedure.
	// Versioned write with no state check: the request carries no "was enabled"
	// guard, so a replay with the version this call just wrote answers ABORTED
	// (optimistic lock conflict) and a re-read followed by another disable
	// succeeds again.
	// Requires organization/write.
	DisableOrganization(context.Context, *connect.Request[v1.DisableOrganizationRequest]) (*connect.Response[v1.DisableOrganizationResponse], error)
	// Grants a user a role in an organization, or updates the role of an existing
	// member.
	// Not convergent: the (organization, user) pair is the primary key and the
	// insert has no upsert, so re-adding an existing member fails as INTERNAL
	// instead of updating its role; use the role-update procedure for that.
	// Fails INVALID_ARGUMENT on an unknown role, NOT_FOUND on an unknown
	// organization, FAILED_PRECONDITION when it is disabled, and PERMISSION_DENIED
	// when the caller is not a member or may not grant the requested role.
	// Requires organization/write.
	AddMember(context.Context, *connect.Request[v1.AddMemberRequest]) (*connect.Response[v1.AddMemberResponse], error)
	// Revokes a user's membership in an organization; the account itself survives.
	// Convergent: removing a member that is already gone answers success.
	// Refused with FAILED_PRECONDITION when it would remove the last platform_admin
	// of the organization, so an organization cannot lose its only administrator.
	// expected_version is not consulted by the current implementation, so it
	// provides no protection against a lost update here.
	// Requires organization/write.
	RemoveMember(context.Context, *connect.Request[v1.RemoveMemberRequest]) (*connect.Response[v1.RemoveMemberResponse], error)
	// Lists the members and roles of one organization.
	// Read-only and replayable, unpaginated.
	// Fails INTERNAL only; an empty organization yields an empty list.
	// Requires member/read.
	ListMembers(context.Context, *connect.Request[v1.ListMembersRequest]) (*connect.Response[v1.ListMembersResponse], error)
	// Changes an existing member's role under optimistic locking, and is the only
	// way to demote or promote without a remove-and-add pair.
	// Conflicts are reported as ABORTED (optimistic lock conflict) when
	// expected_version is stale.
	// Fails INVALID_ARGUMENT on an unknown role, NOT_FOUND when the user is not a
	// member, and FAILED_PRECONDITION when the change would leave no platform_admin.
	// Requires organization/write.
	UpdateMemberRole(context.Context, *connect.Request[v1.UpdateMemberRoleRequest]) (*connect.Response[v1.UpdateMemberRoleResponse], error)
}

