	// Not a credential-preserving operation: every auth session of the user is
	// revoked on success, so the caller must log in again afterwards.
	// A wrong old password answers UNAUTHENTICATED; a store failure during the
	// revocation step fails closed rather than reporting success.
	// The server applies no password strength policy: length and character rules
	// are the caller's responsibility today.
	// Requires an authenticated caller; it always acts on the session's own user, so
	// there is no administrator-reset path here.
	ChangePassword(context.Context, *connect.Request[v1.ChangePasswordRequest]) (*connect.Response[v1.ChangePasswordResponse], error)
	// Creates a local account bound to an organization with one role.
	// Idempotent on the username: an existing name returns that user unchanged and
	// never overwrites its password, so a retry after a lost response converges, and
	// there is no way to use this RPC to reset a password.
	// Fails INVALID_ARGUMENT on an empty username, more than one role or an unknown
	// role, PERMISSION_DENIED when the caller is not a platform_admin, may not grant
	// the target role, or is not a member of the target organization, and
	// FAILED_PRECONDITION when that organization is disabled.
	// Requires the platform_admin role in the organization being written to.
	CreateLocalUser(context.Context, *connect.Request[v1.CreateLocalUserRequest]) (*connect.Response[v1.CreateLocalUserResponse], error)
	// Reads one local account and its aggregated roles by username.
	// Read-only and replayable; NOT_FOUND when no such account exists.
	// Requires auth/read, which the built-in role model gives platform_admin.
	GetLocalUser(context.Context, *connect.Request[v1.GetLocalUserRequest]) (*connect.Response[v1.GetLocalUserResponse], error)
	// Lists local accounts with an opaque cursor and a page size.
	// Read-only and replayable while the cursor is still valid; a cursor the server
	// cannot decode answers INVALID_ARGUMENT (invalid or expired cursor), so resume
	// from the first page instead of retrying the same token.
	// Requires auth/read.
	ListLocalUsers(context.Context, *connect.Request[v1.ListLocalUsersRequest]) (*connect.Response[v1.ListLocalUsersResponse], error)
