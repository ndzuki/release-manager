// File: auth/v1/auth.proto
// Package auth.v1 owns who may act on a deployment: local accounts, sessions,
// bearer tokens, organizations, organization membership, the organization-to-
// customer bindings that scope cross-tenant work, and the readable authorization
// snapshot a caller resolves before acting.
// release-auth (dev port 8085) serves AuthService, OrganizationService,
// BindingService and AuthorizationService. Callers are the browser console, the
// other service binaries (ValidateToken, GetAuthorizationSnapshot) and
// administrative tooling. ExternalIdentityService is declared here but mounted
