	// Declared for operation search across definitions, statuses and time.
	// Not implemented in the release-orchestrator handler: every call answers
	// UNIMPLEMENTED. Enumerate operations through GetOperation and WatchOperation
	// for identifiers you already hold, or through the release definition's own
	// history.
	ListOperations(context.Context, *connect.Request[v1.ListOperationsRequest]) (*connect.Response[v1.ListOperationsResponse], error)
	// Asks the orchestrator to schedule an inventory refresh for one cluster and
	// returns immediately; the agent reports the result through SyncInventory
	// later.
	// Not idempotent: each call enqueues another request with its own identifier,
	// which is harmless but means a retry doubles the work rather than replaying.
	// NOT_FOUND when the cluster is unknown or not under the named customer, and
	// UNAVAILABLE when no agent stream is online to take the request.
	// The response identifier is also echoed in the X-Sync-Request-ID response
	// header for log correlation.
	// Requires release/write.
	TriggerInventorySync(context.Context, *connect.Request[v1.TriggerInventorySyncRequest]) (*connect.Response[v1.TriggerInventorySyncResponse], error)
	// Inventory sync (REQ-017)
	// Records an inventory snapshot reported by an operator agent, marking releases
	// that disappeared from a full snapshot as missing, and answers the accepted and
	// missing counts with the snapshot version.
	// Idempotent on the sync_id field: a report replayed with the same identifier is
	// answered from the recorded result with status duplicate and no second write.
	// This is the only management procedure the customer-cluster agent may call, and
	// it is served on the mTLS agent-gateway listener, where a verified client
	// certificate naming this operator, customer and cluster is the credential; a
	// caller without one is refused before the handler runs. The identity fields must
	// match the certificate, so an agent cannot report for another cluster.
	// INVALID_ARGUMENT for a malformed report or an over-large item list.
	SyncInventory(context.Context, *connect.Request[v1.SyncInventoryRequest]) (*connect.Response[v1.SyncInventoryResponse], error)
