// AuthorizationServiceClient is a client for the auth.v1.AuthorizationService service.
type AuthorizationServiceClient interface {
	// Reads the caller's effective role and capability flags for one organization and
	// customer pair, together with the policy and source versions the answer was
	// computed from.
	// Read-only and replayable, but the versions make the answer explicitly stale-
	// able: a client must re-read rather than cache it indefinitely.
	// Every refusal is deliberately indistinguishable: an unknown scope, a disabled
	// organization or customer, or a missing binding all answer PERMISSION_DENIED
	// with a machine reason code, and an unreadable policy answers UNAVAILABLE
	// (POLICY_UNAVAILABLE) so a client fails closed.
	// Requires valid UUID identifiers for both scope fields.
	GetAuthorizationSnapshot(context.Context, *connect.Request[v1.GetAuthorizationSnapshotRequest]) (*connect.Response[v1.GetAuthorizationSnapshotResponse], error)
	// Grants or revokes a single capability for one subject inside an organization,
	// and returns the new source and policy versions.
	// Convergent: applying the same grant twice leaves one entry, and the versioned
	// update answers ABORTED (AUTHORIZATION_VERSION_CONFLICT) when the store moved
	// underneath it, so the caller re-reads and retries.
	// Fails INVALID_ARGUMENT on a malformed scope or an unsupported action, and
	// PERMISSION_DENIED when the caller is not an administrator, the subject is not
	// an active member, or the scope is unavailable.
	// Requires an administrator role in the target organization; nothing in the
	// product currently calls it, so it exists for operators and future tooling.
	SetCapabilityGrant(context.Context, *connect.Request[v1.SetCapabilityGrantRequest]) (*connect.Response[v1.SetCapabilityGrantResponse], error)
	// Answers whether the caller may act with (object, action) in one organization,
	// and returns the policy-owned scope the caller must apply: whether it may
	// address an organization other than its session organization, and the maximum
	// query window in days.
	// Answers 200 with allowed=false for an ordinary refusal so the caller can map
	// the reason to its own error code; only a malformed request
	// (INVALID_ARGUMENT), a missing identity (UNAUTHENTICATED), or an unreadable
	// policy (UNAVAILABLE / policy_unavailable) is an RPC error, so a caller always
	// fails closed rather than guessing.
	// Authorization is evaluated inside the handler against the caller's persistent
	// membership and the requested scope; the request may not assert an identity or
	// a role.
	AuthorizeAccess(context.Context, *connect.Request[v1.AuthorizeAccessRequest]) (*connect.Response[v1.AuthorizeAccessResponse], error)
}

