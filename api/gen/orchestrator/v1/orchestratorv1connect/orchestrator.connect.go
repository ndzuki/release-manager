	// retry after a lost response must treat that as done.
	// Requires release/write.
	DeleteClusterRoute(context.Context, *connect.Request[v1.DeleteClusterRouteRequest]) (*connect.Response[v1.DeleteClusterRouteResponse], error)
	// Lists the Helm releases recorded in the inventory of one cluster. The answer
	// is the last snapshot the agent reported, not a live query, so freshness is
	// governed by TriggerInventorySync and SyncInventory.
	// Read-only and replayable, with an opaque cursor; a cursor the store cannot
	// decode answers INVALID_ARGUMENT (invalid_cursor).
	// INVALID_ARGUMENT for a missing customer or cluster, or a name search over
	// 253 characters; NOT_FOUND for an unknown customer or cluster.
	// Requires release/read.
	ListReleases(context.Context, *connect.Request[v1.ListReleasesRequest]) (*connect.Response[v1.ListReleasesResponse], error)
	// E2E observability (REQ-066): unfiltered release-inventory enumeration.
	// Each row carries the stable identity of one observed release plus its
	// active (non-terminal) operation when present; used for identity checks,
	// release_busy discovery and e2e-cleanup recovery. values_digest and
	// internal sync data are intentionally not exposed.
	// Enumerates observed release inventory, each row carrying the stable identity
	// of one observed release plus its active operation when there is one.
	// Read-only and replayable, and deliberately unfiltered so that reconciliation
	// and cleanup tooling can walk the whole set; the values digest and internal sync
	// data are not exposed.
	// UNAUTHENTICATED when no caller identity can be resolved.
	// Requires release/read.
	ListReleaseInventory(context.Context, *connect.Request[v1.ListReleaseInventoryRequest]) (*connect.Response[v1.ListReleaseInventoryResponse], error)
